export function getTagEmoji(tag: string) {
	return TAG_EMOJIS[tag.toLocaleLowerCase("ru-RU")] || "🏷️";
}

export function formatTag(tag: string) {
	return `${getTagEmoji(tag)} ${tag}`;
}
